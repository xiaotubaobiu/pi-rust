// cwd-dependent values are encoded so tests can substitute the live cwd:
// - a value embedding the captured cwd verbatim becomes "!CWD" + suffix;
// - any other cwd-derived value (e.g. after ".." pops, or a pure ".." chain)
//   becomes "!REL" + path.relative(capturedCwd, value), which the test
