import pathMod from "node:path";
// Replace the captured cwd prefix with "!CWD" (keeps any suffix such as the
// resolved tail of `path.resolve`). The win32 match is case-insensitive
// because node preserves the drive-letter case of the input.
const ciIndexOf = (haystack, needle) => {
  const h = haystack.toLowerCase();
  const n = needle.toLowerCase();
  return h.indexOf(n);
};
const substituteCwdPartial = (s) => {
  if (ciIndexOf(s, CWD_WIN) !== -1) {
    const i = ciIndexOf(s, CWD_WIN);
    return "!CWD" + s.slice(i + CWD_WIN.length);
  }
  if (ciIndexOf(s, CWD_POSIX) !== -1) {
    const i = ciIndexOf(s, CWD_POSIX);
    return "!CWD" + s.slice(i + CWD_POSIX.length);
  }
  return s;
};
const relEncode = (value, flavor) => {
  if (value.includes(CWD_WIN) || value.includes(CWD_POSIX)) {
    return substituteCwdPartial(value);
  }
  // Only absolute values are re-encoded relative to the captured cwd;
  // already-relative results (e.g. "..\\c" between two absolute inputs) are
  // cwd-independent and stay pinned.
  const absolute = /^[a-zA-Z]:[\\/]/.test(value) || value.startsWith("/") || value.startsWith("\\");
  if (!absolute) {
    return value;
  }
  const captured = flavor === "win32" ? CWD_WIN : CWD_POSIX;
  const rel = flavor === "win32"
    ? pathMod.win32.relative(captured, value)
    : pathMod.posix.relative(captured, value);
  return rel.startsWith("..") ? `!REL${rel}` : value;
};
