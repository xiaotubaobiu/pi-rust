#[cfg(test)]
mod model_catalog {
    use super::*;
    use crate::ai::models::catalog::{
        catalog_provider_ids, embedded_provider_groups, flatten_typed_model_catalog,
    };
    use crate::ai::types::{AnyModel, ModelType};
    use std::collections::BTreeMap;

    fn sorted_map(models: Vec<AnyModel>) -> BTreeMap<String, Value> {
        let mut map = BTreeMap::new();
        for model in models {
            map.insert(model.id().to_string(), serde_json::to_value(&model).unwrap());
        }
        map
    }

    /// The chat flattening contract, pinned against the actual upstream
    /// `flattenChatModelCatalog` over every embedded shard: upstream keeps
    /// entries with `type === "chat"` STRICTLY (the current snapshot's
    /// untyped entries are all excluded), while the port additionally admits
    /// the untyped entries as chat — the documented compatibility rule that
    /// keeps the pre-discriminator snapshot resolving. Admitted entries match
    /// value-for-value.
    #[test]
    fn chat_flatten_matches_upstream_with_documented_untyped_rule() {
        let fixture = &oracle()["modelCatalog"];
        for provider in catalog_provider_ids() {
            let Some(expected) = fixture.get(provider) else {
                continue;
            };
            let groups = embedded_provider_groups(provider)
                .unwrap_or_else(|| panic!("{provider} missing from the embedded snapshot"));
            let actual = sorted_map(flatten_typed_model_catalog(provider, groups, ModelType::Chat));

            let mut expected_chat: BTreeMap<String, Value> = BTreeMap::new();
            for (id, model) in expected["chat"].as_object().unwrap() {
                expected_chat.insert(id.clone(), model.clone());
            }
            for group in groups.as_object().unwrap().values() {
                for (id, entry) in group.as_object().unwrap() {
                    if entry.get("type").is_none() {
                        expected_chat.insert(id.clone(), entry.clone());
                    }
                }
            }
            assert_eq!(actual, expected_chat, "{provider}: chat flatten diverges");
        }
    }

    /// Image and classifier flattening match upstream strictly (no untyped
    /// allowance): every embedded shard is empty on BOTH sides, and the
    /// synthetic mixed shard pins the strict per-type filter against the
    /// actual upstream semantics (`type === "image"` / `=== "classifier"`).
    #[test]
    fn image_and_classifier_flatten_match_upstream() {
        let fixture = &oracle()["modelCatalog"];
        for provider in catalog_provider_ids() {
            let Some(expected) = fixture.get(provider) else {
                continue;
            };
            let groups = embedded_provider_groups(provider).unwrap();
            let image = sorted_map(flatten_typed_model_catalog(provider, groups, ModelType::Image));
            let classifier =
                sorted_map(flatten_typed_model_catalog(provider, groups, ModelType::Classifier));
            let expected_image: BTreeMap<String, Value> = expected["image"]
                .as_object()
                .unwrap()
                .iter()
                .map(|(id, value)| (id.clone(), value.clone()))
                .collect();
            let expected_classifier: BTreeMap<String, Value> = expected["classifier"]
                .as_object()
                .unwrap()
                .iter()
                .map(|(id, value)| (id.clone(), value.clone()))
                .collect();
            assert_eq!(image, expected_image, "{provider} image");
            assert_eq!(classifier, expected_classifier, "{provider} classifier");
        }

        // The synthetic mixed shard: strict per-type selection on both sides
        // (upstream returns only the explicit `type` entries).
        let synthetic = serde_json::json!({
            "openai-completions": {
                "v1": {"id": "v1", "name": "V1", "api": "openai-completions", "provider": "p", "baseUrl": "https://p.example", "type": "chat", "reasoning": false, "input": ["text"], "cost": {"input": 1, "output": 2, "cacheRead": 0, "cacheWrite": 0}, "contextWindow": 8, "maxTokens": 4},
                "v2": {"id": "v2", "name": "V2", "api": "openai-completions", "provider": "p", "baseUrl": "https://p.example", "reasoning": false, "input": ["text"], "cost": {"input": 1, "output": 2, "cacheRead": 0, "cacheWrite": 0}, "contextWindow": 8, "maxTokens": 4}
            },
            "openrouter-images": {
                "i1": {"id": "i1", "name": "I1", "api": "openrouter-images", "provider": "p", "baseUrl": "https://p.example", "type": "image", "input": ["text"], "output": ["image"], "cost": {"input": 1, "output": 2, "cacheRead": 0, "cacheWrite": 0}}
            },
            "typesafe-system-one": {
                "c1": {"id": "c1", "name": "C1", "api": "typesafe-system-one", "provider": "p", "baseUrl": "https://p.example", "type": "classifier", "input": ["text"], "cost": {"input": 1, "output": 2, "cacheRead": 0, "cacheWrite": 0}, "contextWindow": 16}
            }
        });
        let expected = &fixture["<synthetic>"];
        // Upstream: only the explicit `type: "chat"` entry is a chat model;
        // the untyped v2 is excluded.
        let upstream_chat_keys: Vec<&str> =
            expected["chat"].as_object().unwrap().keys().map(String::as_str).collect();
        assert_eq!(upstream_chat_keys, ["v1"]);
        assert_eq!(
            expected["image"].as_object().unwrap().keys().map(String::as_str).collect::<Vec<_>>(),
            ["i1"]
        );
        assert_eq!(
            expected["classifier"].as_object().unwrap().keys().map(String::as_str).collect::<Vec<_>>(),
            ["c1"]
        );
        // The port's strict image/classifier flatten agrees exactly (values
        // included).
        let image = sorted_map(flatten_typed_model_catalog("p", &synthetic, ModelType::Image));
        let classifier =
            sorted_map(flatten_typed_model_catalog("p", &synthetic, ModelType::Classifier));
        assert_eq!(image.len(), 1);
        assert_eq!(image["i1"], expected["image"]["i1"]);
        assert_eq!(classifier.len(), 1);
        assert_eq!(classifier["c1"], expected["classifier"]["c1"]);
        // And the port's chat flatten admits both the explicit and the
        // untyped chat entries (the documented superset rule).
        let chat = sorted_map(flatten_typed_model_catalog("p", &synthetic, ModelType::Chat));
        let chat_keys: Vec<String> = chat.keys().cloned().collect();
        assert_eq!(chat_keys, vec!["v1".to_string(), "v2".to_string()]);
    }
}
