    #[tokio::test]
    async fn typesafe_happy_path_matches_upstream_capture() {
        let server = MockServer::start().await;
        let response = &fixture()["typesafe"];
        // The canned SERVER body from the capture (wire-level noul answers).
        let canned = response["canned"].clone();
        Mock::given(method("POST"))
            .and(path("/systemone"))
            .respond_with(ResponseTemplate::new(200).set_body_json(canned))
            .expect(1)
            .mount(&server)
            .await;

        let model = typesafe_model(&format!("{}/", server.uri()));
        let result = classify_typesafe(&model, &oracle_context(), Some(&options())).await;

        // Request shape: method, path, and every captured header value.
        let captured = &response["requests"][0];
        assert_eq!(captured["method"].as_str().unwrap(), "POST");
        assert!(captured["url"].as_str().unwrap().ends_with("/systemone"));
        let requests = server.received_requests().await.unwrap();
        let sent = requests.last().unwrap();
        for (name, value) in captured["headers"].as_object().unwrap() {
            let wire = sent
                .headers
                .get(name)
                .and_then(|value| value.to_str().ok());
            assert_eq!(wire, Some(value.as_str().unwrap()), "header {name}");
        }
        // Body: key-set/value equality against the captured wire bytes (the
        // port's BTreeMap carrier serializes sorted keys; the fixture's keys
        // are already sorted, so the parsed objects are equal).
        let body: Value = serde_json::from_slice(&sent.body).unwrap();
        let expected_body: Value =
            serde_json::from_str(captured["body"].as_str().unwrap()).unwrap();
        assert_eq!(body, expected_body);

        // Result: answers and catalog-priced usage match the capture.
        assert_eq!(result.stop_reason, ClassifierStopReason::Stop, "err: {:?}", result.error_message);
        assert!(result.error_message.is_none());
        let answers = serde_json::to_value(result.answers).unwrap();
        assert_eq!(answers, response["result"]["answers"]);
        let usage = serde_json::to_value(result.usage).unwrap();
        assert_eq!(usage["input"], response["result"]["usage"]["input"]);
        assert_eq!(usage["output"], response["result"]["usage"]["output"]);
        assert_eq!(usage["totalTokens"], response["result"]["usage"]["totalTokens"]);
        for bucket in ["input", "output", "cacheRead", "cacheWrite", "total"] {
            let actual = usage["cost"][bucket].as_f64().unwrap();
            let expected = response["result"]["usage"]["cost"][bucket].as_f64().unwrap();
            assert!(
                (actual - expected).abs() < 1e-15,
                "cost.{bucket}: {actual} vs {expected}"
            );
        }
    }

