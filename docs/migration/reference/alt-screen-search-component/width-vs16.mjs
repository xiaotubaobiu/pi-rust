// Additive correction: the inherited RGI enumerator missed standalone scalar+VS16.
// Enumerate every scalar against the native regex; actual upstream utils supply
// the new independent width expectations. No UI expected output feeds the table.
import assert from 'node:assert/strict';
import {readFileSync,writeFileSync} from 'node:fs';
import {dirname,resolve,join} from 'node:path';
import {fileURLToPath,pathToFileURL} from 'node:url';
import {createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';
const here=dirname(fileURLToPath(import.meta.url));
const root=resolve(here,'../../../..');
const scratch=join(root,'target/alt-screen-search-component-oracle');
const {visibleWidth,truncateToWidth,sliceByColumn}=await import(pathToFileURL(join(scratch,'src/utils.ts')));
const {AltScreenSearchComponent}=await import(pathToFileURL(join(scratch,'src/alt-screen-search.ts')));
const RGI=/^\p{RGI_Emoji}$/v,accepted=[];
let scanned=0;
for(let point=0;point<=0x10ffff;point++){
 if(point>=0xd800&&point<=0xdfff)continue;
 scanned++;
 if(RGI.test(String.fromCodePoint(point)+'\ufe0f'))accepted.push(point);
}
const set=new Set(accepted),cases=[];
const add=text=>cases.push({text,width:visibleWidth(text),rgi:RGI.test(text),truncate:[0,1,2,3,4,5].map(w=>truncateToWidth(text,w,'')),slices:[0,1,2].map(start=>sliceByColumn(text,start,1,true))});
for(const point of accepted){
 const base=String.fromCodePoint(point);
 for(const text of [base,base+'\ufe0e',base+'\ufe0f',base+'\ufe0f\ufe0f',base+'\ufe0f\u0301','x'+base+'\ufe0f'+'y'])add(text);
}
for(let point=0;point<128;point++)if(!set.has(point))add(String.fromCodePoint(point)+'\ufe0f');
for(let point=128;point<0x3100;point+=257)if(!set.has(point))add(String.fromCodePoint(point)+'\ufe0f');
for(let point=0x1f000;point<0x1fc00;point+=16)if(!set.has(point))add(String.fromCodePoint(point)+'\ufe0f');
const table=`// @generated by docs/migration/reference/alt-screen-search-component/width-vs16.mjs.
// All Unicode scalar+VS16 pairs accepted by Node ${process.version} (Unicode ${process.versions.unicode})
// /^\\p{RGI_Emoji}$/v. Supplements, never rewrites, the inherited sequence table.
// This is general runtime property data, not search/UI expected output.
const VS16_BASES: &[u32] = &[
${accepted.map(point=>'    0x'+point.toString(16)+',').join('\n')}
];

pub(crate) fn is_rgi_emoji(segment: &str) -> bool {
    if super::rgi_emoji::is_rgi_emoji(segment) {
        return true;
    }
    let mut chars = segment.chars();
    let Some(first) = chars.next() else {
        return false;
    };
    chars.next() == Some('\\u{fe0f}')
        && chars.next().is_none()
        && VS16_BASES.binary_search(&(first as u32)).is_ok()
}
`;
writeFileSync(join(scratch,'rgi_emoji_vs16.rs'),table);
execFileSync('rustfmt',['--edition','2021',join(scratch,'rgi_emoji_vs16.rs')]);
const queries=[],component=new AltScreenSearchComponent(q=>queries.push(q));
const rendered8=component.render(8);
const rect=[component.previousButtonStart,component.previousButtonEnd,component.nextButtonStart,component.nextButtonEnd];
component.handleInput('\x1b[200~a\nb\x1b[201~c');
const firstQuery=[...queries];component.handleInput('\x7f');
assert.deepEqual(rect,[2,3,4,5]);assert.deepEqual(firstQuery,['abc']);assert.deepEqual(queries,['abc','ab']);
const fixture={scannedScalars:scanned,acceptedBases:accepted,cases,independent:{rendered8,rect,firstQuery,afterBackspace:[...queries]}};
writeFileSync(join(scratch,'width-vs16-fixtures.json'),JSON.stringify(fixture,null,2)+'\n');
const sha=b=>createHash('sha256').update(b).digest('hex');
const files=Object.fromEntries(['rgi_emoji_vs16.rs','width-vs16-fixtures.json'].map(name=>{const b=readFileSync(join(scratch,name));return[name,{bytes:b.length,sha256:sha(b)}];}));
writeFileSync(join(scratch,'width-vs16-manifest.json'),JSON.stringify({node:process.version,unicode:process.versions.unicode,rustfmt:execFileSync('rustfmt',['--version'],{encoding:'utf8'}).trim(),generatorSha256:sha(readFileSync(fileURLToPath(import.meta.url))),upstreamUtilsSha256:sha(readFileSync(join(scratch,'src/utils.ts'))),upstreamComponentSha256:sha(readFileSync(join(scratch,'src/alt-screen-search.ts'))),scannedScalars:scanned,acceptedBases:accepted.length,cases:cases.length,artifacts:files},null,2)+'\n');
console.log(JSON.stringify({scanned,acceptedBases:accepted.length,cases:cases.length,independent:fixture.independent,artifacts:files}));
