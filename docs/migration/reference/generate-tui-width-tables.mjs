function getActiveBackgroundAnsi(text) {
	// Local re-implementation for the oracle runner only: upstream does not
	// export AnsiCodeTracker, and getActiveBackgroundAnsi is not exported from
	// utils.ts. It reuses the exported primitives so the oracle still runs the
	// same parsing code paths (extractAnsiCode + SGR tracking semantics).
	const tracker = { bg: null, params: [] };
	const codes = [];
	let i = 0;
	let active = null;
	while (i < text.length) {
		const ansi = extractAnsiCodeFrom(text, i);
		if (ansi) {
			const m = ansi.code.match(/^\x1b\[([\d;]*)m$/);
			if (m) {
				const params = m[1] === "" ? ["0"] : m[1].split(";");
				for (let k = 0; k < params.length; k++) {
					const code = Number.parseInt(params[k], 10);
					if ((code === 38 || code === 48) && params[k + 1] === "5" && params[k + 2] !== undefined) {
						const color = params.slice(k, k + 3).join(";");
						if (code === 48) tracker.bg = color;
						k += 2;
					} else if ((code === 38 || code === 48) && params[k + 1] === "2" && params[k + 4] !== undefined) {
						const color = params.slice(k, k + 5).join(";");
						if (code === 48) tracker.bg = color;
						k += 4;
					} else if (code === 0) {
						tracker.bg = null;
					} else if (code === 49) {
						tracker.bg = null;
					} else if ((code >= 40 && code <= 47) || (code >= 100 && code <= 107)) {
						tracker.bg = String(code);
					}
				}
			}
			i += ansi.length;
		} else {
			i++;
		}
	}
	return tracker.bg === null ? "" : "\x1b[" + tracker.bg + "m";

	function extractAnsiCodeFrom(str, pos) {
		if (pos >= str.length || str[pos] !== "\x1b") return null;
		const next = str[pos + 1];
		if (next === "[") {
			let j = pos + 2;
			while (j < str.length && !/[mGKHJ]/.test(str[j])) j++;
			if (j < str.length) return { code: str.substring(pos, j + 1), length: j + 1 - pos };
			return null;
		}
		if (next === "]" || next === "_") {
			let j = pos + 2;
			while (j < str.length) {
				if (str[j] === "\x07") return { code: str.substring(pos, j + 1), length: j + 1 - pos };
				if (str[j] === "\x1b" && str[j + 1] === "\\") return { code: str.substring(pos, j + 2), length: j + 2 - pos };
				j++;
			}
			return null;
		}
		return null;
	}
}

